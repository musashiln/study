#include <stdio.h>

// 注意：“不能通过指针修改值”不代表这个值绝对不会变化，它仍然可能通过原变量或其他可写指针被修改。

// 记忆方法：const 在 * 前面，限制 *A；在 * 后面，限制 A。
int main(void) {
    int x = 10, y = 20;

    const int *p = &x;
    p = &y;       // 可以：改变指向
    // *p = 30;   // 不可以：不能通过 p 修改整数
    x = 30;       // 可以：x 本身不是常量

    int *const q = &x;
    *q = 40;      // 可以：修改指向的整数
    // q = &y;    // 不可以：q 的指向固定

    const int *const r = &x;
    // *r = 50;   // 不可以
    // r = &y;    // 不可以

}