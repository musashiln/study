//写一个函数把一个10进制数按照二进制格式输出
#include <stdio.h>
void printBinary(int num);
int main() {
    printBinary(13);
}
void printBinary(int num){
    int len = sizeof(int)*8;
    int temp;
    for (int i=0; i<len; i++) {
        temp = num; //每次都在原数的基础上进行移位运算
        temp = temp>>(31-i); //每次移动的位数
        int t = temp&1; //取出最后一位
        if(i!=0&&i%4==0)
            printf(" "); 
        printf("%d",t);
    }
}
