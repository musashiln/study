// 按位异或
// 当对应的二进位相异（不相同）时，结果为1，否则为0
// 规律:
// 相同整数相的结果是0。比如55=0
// 多个整数相^的结果跟顺序无关。例如: 567=576
// 同一个数异或另外一个数两次, 结果还是那个数。例如: 577 = 5

/*
   偶数: 的二进制是以0结尾
   8   -> 1000
   10  -> 1010
   
   奇数: 的二进制是以1结尾
   9   -> 1001
   11  -> 1011

   任何数和1进行&操作,得到这个数的最低位
   1000
  &0001
   -----
   0000  // 结果为0, 代表是偶数

   1011
  &0001
   -----
   0001 // 结果为1, 代表是奇数

*/


